<?php
$seven = 7;                                             // Definição de variável
for ($i = 0; $i <= 10; $i++) {                           // Definição de variável + Condição + Passo
    $result = $seven * $i;                              // Processamento
    echo $seven . ' x ' . $i . ' = ' . $result . '<br/>';  // Resultado + Apresentação
}
